export function getOrderStatusCopy(status: string, locale: "en" | "ar") {
  const localized = orderStatuses[status]?.[locale];
  if (localized) return { label: localized[0], description: localized[1] };
  return {
    label: status
      .replaceAll("_", " ")
      .toLowerCase()
      .replace(/^./, (letter) => letter.toUpperCase()),
    description:
      locale === "ar"
        ? "راجعي هذا الطلب للحصول على أحدث حالة."
        : "Review this order for its latest status.",
  };
}

export function useI18n() {
  const { locale } = useStore();
  return {
    locale,
    t: (key: MessageKey) => messages[locale][key],
  };
}
